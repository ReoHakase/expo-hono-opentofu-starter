import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';

const services = ['api', 'metro', 'google', 'apple', 'mail'] as const;
const root = fileURLToPath(new URL('../', import.meta.url));

export function deviceOrigin(output: string): string {
  const url = new URL(output.trim());
  if (
    url.protocol !== 'https:' ||
    !url.hostname.endsWith('.localhost') ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== '/'
  ) {
    throw new Error(
      'Expected an HTTPS .localhost route. Start the Portless HTTPS proxy; export PORTLESS_STATE_DIR if it uses a custom state directory.',
    );
  }
  return url.origin;
}

function startDevices() {
  const env: NodeJS.ProcessEnv = { ...process.env, PORTLESS_HTTPS: '1', PORTLESS_PORT: '443' };
  // Bun may have loaded the root dotenv with shell interpolation. Let Compose read it itself.
  delete env.WORKTREE_ROOT;
  delete env.WORKTREE_GIT_COMMON_DIR;
  delete env.WORKTREE_ID;
  delete env.COMPOSE_PROJECT_NAME;
  delete env.DEVICE_EXPO_ORIGIN;
  for (const service of services) {
    delete env[`DEVICE_${service.toUpperCase()}_ORIGIN`];
  }
  const options = { cwd: root, env };
  execFileSync('sh', ['scripts/worktree-init.sh'], { ...options, stdio: 'inherit' });
  const { COMPOSE_PROJECT_NAME: project } = parseEnv(
    readFileSync(new URL('../.env', import.meta.url), 'utf8'),
  );
  if (!project) {
    throw new Error('Compose project identity is missing');
  }
  // Validate before recreating containers. Compose already includes the worktree in its project.
  const endpoints = services.map((service) => ({
    service,
    origin: deviceOrigin(
      execFileSync('portless', ['get', `${service}.${project}`, '--no-worktree'], {
        ...options,
        encoding: 'utf8',
      }),
    ),
  }));
  execFileSync('portless', ['compose', 'up', '-d', '--build', 'api', 'metro'], {
    ...options,
    stdio: 'inherit',
  });
  writeFileSync(
    new URL('../.env.devices', import.meta.url),
    '# Generated by scripts/devices.ts; from Portless HTTPS routes.\n' +
      endpoints
        .map(
          ({ service, origin }) =>
            `DEVICE_${service.toUpperCase()}_ORIGIN=${origin}\n` +
            (service === 'metro'
              ? `DEVICE_EXPO_ORIGIN=${origin.replace('https:', 'exps:')}\n`
              : ''),
        )
        .join(''),
    { mode: 0o600 },
  );
  execFileSync(
    'portless',
    [
      'compose',
      '--env-file',
      '.env',
      '--env-file',
      '.env.devices',
      '-f',
      'compose.yaml',
      '-f',
      'compose.devices.yaml',
      'up',
      '-d',
      '--wait',
      'api',
      'metro',
    ],
    { ...options, stdio: 'inherit' },
  );
  writeFileSync(
    new URL('../.env.devices.hosts', import.meta.url),
    `# ${project}\n127.0.0.1 ${endpoints.map(({ origin }) => new URL(origin).hostname).join(' ')}\n`,
    { mode: 0o600 },
  );
  for (const { service, origin } of endpoints) {
    console.log(`${service}: ${origin}`);
  }
  const ports = new Set(endpoints.map(({ origin }) => new URL(origin).port || '443'));
  console.log('\nAndroid: replace SERIAL with the target from adb devices -l');
  for (const port of ports) {
    console.log(`adb -s SERIAL reverse tcp:${port} tcp:${port}`);
  }
  console.log('\nRemove shared proxy forwarding only after all worktrees on this device stop:');
  for (const port of ports) {
    console.log(`adb -s SERIAL reverse --remove tcp:${port}`);
  }
  console.log('\nInstall the Portless public CA on the device; never copy ca-key.pem.');
  console.log('Merge .env.devices.hosts into Android emulator hosts; see docs/setup.md.');
  console.log('\nOpen the metro URL in your Development Build. Run bun run devices on the host.');
}

if (import.meta.main) {
  startDevices();
}
