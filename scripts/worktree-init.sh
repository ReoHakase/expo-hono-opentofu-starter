#!/bin/sh
set -eu

# Runs on the host before a Dev Container exists; requires only Git and POSIX tools.
worktree_root=$(CDPATH='' cd -- "${1:-$(dirname "$0")/..}" && pwd -P)
git_common_dir=$(git -C "$worktree_root" rev-parse --path-format=absolute --git-common-dir)
case "$worktree_root$git_common_dir" in
  *'
'*) echo 'Checkout paths must not contain newlines.' >&2; exit 1 ;;
esac
if [ -f "$worktree_root/.env" ] && [ "$(head -n 1 "$worktree_root/.env")" != '# Generated by scripts/worktree-init.sh' ]; then
  echo 'Root .env is reserved for generated Compose settings. Move custom values to apps/api/.env or apps/mobile/.env.' >&2
  exit 1
fi
quote_env() { printf '%s' "$1" | sed "s/'/\\\\'/g"; }
umask 077
temporary=$(mktemp "$worktree_root/.env.XXXXXX")
trap 'rm -f "$temporary"' 0
cat > "$temporary" <<EOF
# Generated by scripts/worktree-init.sh
WORKTREE_ROOT='$(quote_env "$worktree_root")'
WORKTREE_GIT_COMMON_DIR='$(quote_env "$git_common_dir")'
EOF
mv "$temporary" "$worktree_root/.env"
